import { appendFileSync, copyFileSync, existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs'
import { join } from 'node:path'
import { fileURLToPath } from 'node:url'
import { SCHEMA_FILE } from './load.ts'
import { display } from './paths.ts'

const STARTER = fileURLToPath(new URL('../../templates/topology.yaml', import.meta.url))
const EXAMPLE = fileURLToPath(new URL('../../examples/acme/topology.yaml', import.meta.url))

/** Write the schema next to a topology file, for editor autocomplete. Re-run after upgrading. */
export function writeSchema(dir: string) {
  const target = join(dir, 'topology.schema.json')
  copyFileSync(SCHEMA_FILE, target)
  return target
}

/** A starter topology.yaml (or the Acme example), the schema, and .malha/ in .gitignore. */
export function init(dir: string, opts: { force: boolean; example: boolean }) {
  mkdirSync(dir, { recursive: true })
  const target = join(dir, 'topology.yaml')
  if (existsSync(target) && !opts.force) throw new Error(`${display(target)} already exists (use --force to overwrite)`)
  writeFileSync(target, readFileSync(opts.example ? EXAMPLE : STARTER, 'utf8'))
  writeSchema(dir)

  const ignore = join(dir, '.gitignore')
  const lines = existsSync(ignore) ? readFileSync(ignore, 'utf8').split('\n') : []
  if (!lines.includes('.malha/')) appendFileSync(ignore, `${lines.length && lines.at(-1) !== '' ? '\n' : ''}# Generated by malha (the dependency scan)\n.malha/\n`)

  const rel = display(target)
  console.log(`Wrote ${rel}, topology.schema.json and a .gitignore entry for .malha/.

Next:
  malha dev ${rel}        open it in the browser; edits reload the page
  malha validate ${rel}   check it, e.g. in CI`)
}
